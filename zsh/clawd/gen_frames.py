"""Generate Clawd's dance frames for clawd.zsh.

Clawd is drawn on a pixel grid and packed into quadrant block characters
(each cell = 2x2 pixels), so he can hop and sway by half a cell.

  python3 gen_frames.py > frames.zsh   (run inside zsh/clawd/)
"""
W, H = 20, 8          # pixel grid -> 10 cols x 4 rows
QUAD = " ▘▝▀▖▌▞▛▗▚▐▜▄▙▟█"  # bits: TL=1 TR=2 BL=4 BR=8

ARMS = {  # left arm pixels; the right arm mirrors them
    "out":  [(1, 2), (2, 2)],
    "up":   [(1, 0), (2, 1)],
    "down": [(2, 3), (1, 4)],
}
LEGS = {
    "stand": [4, 6, 11, 13],
    "wide":  [3, 5, 12, 14],
    "left":  [3, 5, 10, 12],
    "right": [5, 7, 12, 14],
}
EYES = {"front": (5, 12), "left": (4, 11), "right": (6, 13), "shut": ()}


def sprite(left="out", right="out", legs="stand", eyes="front"):
    px = set()
    for x in range(3, 15):
        px |= {(x, 0), (x, 1), (x, 2), (x, 3)}
    for x in EYES[eyes]:
        px.discard((x, 1))
    px |= set(ARMS[left])
    px |= {(17 - x, y) for x, y in ARMS[right]}
    px |= {(x, 4) for x in LEGS[legs]}
    return px


def frame(dx=0, dy=2, **pose):
    px = {(x + dx, y + dy) for x, y in sprite(**pose)}
    rows = []
    for r in range(H // 2):
        line = ""
        for c in range(W // 2):
            b = sum(bit for bit, (ox, oy) in zip((1, 2, 4, 8), ((0, 0), (1, 0), (0, 1), (1, 1)))
                    if (2 * c + ox, 2 * r + oy) in px)
            line += QUAD[b]
        rows.append(line.rstrip())
    return "\n".join(rows)


# one bar of dance; the intro plays it once, `clawd` loops it
DANCE = [
    frame(),
    frame(dy=3, left="down", right="down", legs="wide"),
    frame(dy=1, left="up", right="up"),
    frame(dx=-1, left="up", right="down", legs="left", eyes="left"),
    frame(dy=3, left="down", right="down", legs="wide", eyes="left"),
    frame(dx=1, left="down", right="up", legs="right", eyes="right"),
    frame(dy=3, left="down", right="down", legs="wide", eyes="right"),
    frame(dy=1, left="up", right="up", eyes="shut"),
    frame(dy=0, left="up", right="up"),
    frame(dy=3, legs="wide"),
]
REST = frame()
BLINK = frame(eyes="shut")


def zq(s):
    return "$'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


print("# Generated by gen_frames.py — do not edit by hand.")
print("typeset -ga _clawd_dance=(")
for f in DANCE:
    print("  " + zq(f))
print(")")
print("typeset -g _clawd_rest=" + zq(REST))
print("typeset -g _clawd_blink=" + zq(BLINK))
